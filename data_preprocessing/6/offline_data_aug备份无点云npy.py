    for folder in (*METADATA_DIRS, *IMAGE_DIRS):
        src_dir = scene_dir / folder
        dst_dir = output_dir / folder
        if not src_dir.exists():
            continue
        for src_path in src_dir.iterdir():
            if src_path.is_file():
                shutil.copy2(src_path, dst_dir / src_path.name)

    point_cloud_dir = scene_dir / POINT_CLOUD_DIR
    if point_cloud_dir.exists():
        dst_dir = output_dir / POINT_CLOUD_DIR
        dst_dir.mkdir(parents=True, exist_ok=True)
        for src_path in point_cloud_dir.iterdir():
            if src_path.is_file():
                shutil.copy2(src_path, dst_dir / src_path.name)


