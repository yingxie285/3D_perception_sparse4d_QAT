def build_pcd_dtype(
    fields: Sequence[str],
    sizes: Sequence[int],
    types: Sequence[str],
    counts: Sequence[int],
) -> np.dtype:
    dtype_fields: List[Tuple[Any, ...]] = []
    for field_name, field_size, field_type, field_count in zip(
        fields, sizes, types, counts
    ):
        if field_type == "F":
            field_dtype = {4: np.float32, 8: np.float64}.get(field_size)
        elif field_type == "U":
            field_dtype = {1: np.uint8, 2: np.uint16, 4: np.uint32, 8: np.uint64}.get(
                field_size
            )
        elif field_type == "I":
            field_dtype = {1: np.int8, 2: np.int16, 4: np.int32, 8: np.int64}.get(
                field_size
            )
        else:
            field_dtype = None
        if field_dtype is None:
            raise ValueError(
                "Unsupported PCD field spec: "
                f"name={field_name}, size={field_size}, type={field_type}"
            )
        if int(field_count) == 1:
            dtype_fields.append((field_name, field_dtype))
        else:
            dtype_fields.append((field_name, field_dtype, (int(field_count),)))
    return np.dtype(dtype_fields)


def load_binary_pcd(path: Path) -> Tuple[List[str], np.ndarray]:
    header_lines: List[str] = []
    with path.open("rb") as handle:
        while True:
            raw_line = handle.readline()
            if not raw_line:
                raise ValueError(f"Invalid PCD file without DATA header: {path}")
            line = raw_line.decode("utf-8").strip()
            header_lines.append(line)
            if line.upper().startswith("DATA"):
                if "binary" not in line.lower():
                    raise ValueError(f"Only binary PCD is supported: {path}")
                break

        fields = None
        sizes = None
        types = None
        counts = None
        for line in header_lines:
            if line.upper().startswith("FIELDS "):
                fields = line.split()[1:]
            elif line.upper().startswith("SIZE "):
                sizes = [int(value) for value in line.split()[1:]]
            elif line.upper().startswith("TYPE "):
                types = line.split()[1:]
            elif line.upper().startswith("COUNT "):
                counts = [int(value) for value in line.split()[1:]]

        if fields is None or sizes is None or types is None:
            raise ValueError(f"Missing required PCD header fields in {path}")
        if counts is None:
            counts = [1 for _ in fields]
        if not (len(fields) == len(sizes) == len(types) == len(counts)):
            raise ValueError(f"PCD header field lengths do not match in {path}")

        point_cloud = np.fromfile(
            handle,
            dtype=build_pcd_dtype(fields, sizes, types, counts),
        )
    return header_lines, point_cloud


def save_binary_pcd(
    path: Path, header_lines: Sequence[str], point_cloud: np.ndarray
) -> None:
    with path.open("wb") as handle:
        for line in header_lines:
            handle.write((line.rstrip("\n") + "\n").encode("utf-8"))
        point_cloud.tofile(handle)


def load_frame_point_cloud(scene_dir: Path, frame_id: str) -> List[Dict[str, Any]]:
    point_cloud_dir = scene_dir / POINT_CLOUD_DIR
    if not point_cloud_dir.exists():
        return []

    point_cloud_entries: List[Dict[str, Any]] = []
    for src_path in find_point_cloud_files(point_cloud_dir, frame_id):
        suffix = src_path.suffix.lower()
        if suffix == ".npy":
            point_cloud_entries.append(
                {
                    "suffix": suffix,
                    "point_cloud": np.load(str(src_path)),
                    "pcd_header_lines": None,
                }
            )
        elif suffix == ".pcd":
            pcd_header_lines, point_cloud = load_binary_pcd(src_path)
            point_cloud_entries.append(
                {
                    "suffix": suffix,
                    "point_cloud": point_cloud,
                    "pcd_header_lines": pcd_header_lines,
                }
            )
    return point_cloud_entries


def augment_point_cloud(point_cloud: np.ndarray, do_flip: bool) -> np.ndarray:
    augmented = np.array(point_cloud, copy=True)
    if not do_flip:
        return augmented

    if augmented.dtype.names is not None:
        if "y" in augmented.dtype.names:
            augmented["y"] = -augmented["y"]
        return augmented

    if augmented.ndim == 2 and augmented.shape[1] >= 2:
        augmented[:, 1] = -augmented[:, 1]
    elif augmented.ndim == 1 and augmented.shape[0] >= 2:
        augmented[1] = -augmented[1]
    return augmented


def save_augmented_point_cloud(
    point_cloud_entries: Sequence[Mapping[str, Any]],
    output_dir: Path,
    new_frame_id: str,
    do_flip: bool,
) -> int:
    saved_count = 0
    for point_cloud_entry in point_cloud_entries:
        suffix = str(point_cloud_entry["suffix"]).lower()
        point_cloud = augment_point_cloud(
            np.asarray(point_cloud_entry["point_cloud"]),
            do_flip=do_flip,
        )
        dst_path = output_dir / POINT_CLOUD_DIR / f"{new_frame_id}{suffix}"
        dst_path.parent.mkdir(parents=True, exist_ok=True)
        if suffix == ".npy":
            np.save(str(dst_path), point_cloud)
        elif suffix == ".pcd":
            save_binary_pcd(
                dst_path,
                point_cloud_entry.get("pcd_header_lines", []),
                point_cloud,
            )
        else:
            continue
        saved_count += 1
    return saved_count


def save_augmented_images(
    source_images: Mapping[str, Tuple[np.ndarray, str]],
    output_dir: Path,
    new_frame_id: str,
    do_flip: bool,
    photometric_plan: Mapping[str, Any],
    seed: int,
) -> None:
    for image_dir, (source_image, suffix) in source_images.items():
        image = source_image.copy()
        if do_flip:
            image = cv2.flip(image, 1)

        image_rng = stable_rng(seed, new_frame_id, image_dir)
        image = apply_photometric_plan(image, photometric_plan, image_rng)

        dst_path = output_dir / image_dir / f"{new_frame_id}{suffix}"
        dst_path.parent.mkdir(parents=True, exist_ok=True)
        if not cv2.imwrite(str(dst_path), image):
            raise RuntimeError(f"Failed to write image: {dst_path}")


