import torch
import matplotlib.pyplot as plt
import numpy as np

def plot_tensor_histogram(tensor_data, bins=30, range_min=None, range_max=None):
    """
    绘制给定 tensor 的置信度分布直方图，自动调整范围并处理异常值。
    :param tensor_data: PyTorch tensor，表示置信度分数
    :param bins: 直方图的 bin 数量（默认30）
    :param range_min: 直方图的最小范围（自动计算）
    :param range_max: 直方图的最大范围（自动计算）
    """
    if not isinstance(tensor_data, torch.Tensor):
        raise TypeError("输入数据必须是 PyTorch Tensor")
    
    if tensor_data.numel() == 0:
        raise ValueError("输入张量不能为空")
    
    # 转换为 NumPy 数组并过滤无效值
    data_np = tensor_data.cpu().numpy().flatten()
    data_np = data_np[~np.isnan(data_np) & ~np.isinf(data_np)]  # 过滤 NaN 和 inf
    
    if len(data_np) == 0:
        raise ValueError("输入数据均为无效值（NaN/inf）")
    
    # 自动计算范围（如果未指定）
    range_min = data_np.min() if range_min is None else range_min
    range_max = data_np.max() if range_max is None else range_max
    
    plt.figure(figsize=(8, 6))
    plt.hist(
        data_np, 
        bins=bins, 
        range=(range_min, range_max), 
        alpha=0.75, 
        color='b', 
        edgecolor='black'
    )
    plt.xlabel("Confidence Score")
    plt.ylabel("Count")
    plt.title(f"Confidence Scores Distribution (Range: {range_min:.2f}-{range_max:.2f})")
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    plt.show()

